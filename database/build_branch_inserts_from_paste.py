#!/usr/bin/env python3
"""
Read database/branches_paste_raw.txt (one branch per line, as pasted: N.Name,Address,...,State,lat,lng,hours).
Emit database/insert-branches-from-paste.sql (DECLARE @Branches + INSERT INTO BRANCHES + weekly hours).

Parsing: strip leading index; fix known typos; anchor tail as ,lat,lng,hours
  where hours matches Mon-Fri…; state = segment before lat; name = first segment; address = middle.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RAW_PATH = ROOT / "branches_paste_raw.txt"
OUT_PATH = ROOT / "insert-branches-from-paste.sql"

TAIL_RE = re.compile(
    r",\s*(?P<lat>-?\d+\.\d+)\s*,\s*(?P<lng>-?\d+\.\d+)\s*,\s*(?P<hours>Mon[^\n,]*?)\s*$",
    re.IGNORECASE,
)


# Map source state labels onto the customer app filter list (apps/customer/src/constants/malaysiaStates.ts).
STATE_ALIASES = {
    "wilayah persekutuan kuala lumpur": "Kuala Lumpur",
    "wp kuala lumpur": "Kuala Lumpur",
    "wilayah persekutuan labuan": "Labuan",
    "wilayah persekutuan putrajaya": "Putrajaya",
    "penang": "Pulau Pinang",
    "malacca": "Melaka",
}


def normalize_line(s: str) -> str:
    s = s.replace("\u201c", '"').replace("\u201d", '"').replace("\u2018", "'").replace("\u2019", "'")
    s = s.replace("\u3001", ",").replace("，", ",")  # some CJK commas
    s = s.replace("`", "'")
    # Kota Damansara row: hours appear before lat/lng — move to end: ,Mon-Fri…lat,lng -> ,lat,lng,Mon-Fri…
    s = re.sub(
        r",\s*(Mon[-\s]?Fri\s+9:30[-\s]?16:00)\s*(\d+\.\d+)\s*,\s*(\d+\.\d+)\s*,?\s*$",
        r",\2,\3,\1",
        s,
        flags=re.I,
    )
    # Segambut-style double comma before hours: ,lat,lng,,Mon
    s = re.sub(r",(\d+\.\d+)\s*,\s*,\s*(Mon)", r",\1,\2", s, flags=re.I)
    return s.strip()


def strip_index(s: str) -> str:
    s = re.sub(r"^[\s—\-\.0-9]+", "", s)
    return s.lstrip(". ").strip()


def parse_line(line: str) -> tuple[str, str, str, float, float, str] | None:
    line = normalize_line(line)
    if not line or line.startswith("—") or line.startswith("-" * 5):
        return None
    if not re.search(r"\d+\.\d+", line):
        return None
    line = strip_index(line)
    m = TAIL_RE.search(line)
    if not m:
        return None
    lat = float(m.group("lat"))
    lng = float(m.group("lng"))
    hours = m.group("hours").strip()
    prefix = line[: m.start()]
    parts = [p.strip() for p in prefix.split(",") if p.strip() != ""]
    if len(parts) < 2:
        return None
    name = parts[0].strip().strip('"').strip()
    state = parts[-1].strip().strip('"').strip()
    state = STATE_ALIASES.get(state.lower(), state)
    address = ", ".join(parts[1:-1]).strip().strip('"').strip() if len(parts) > 2 else ""
    if not name or not state or not address:
        return None
    if len(name) > 200:
        name = name[:200]
    if len(address) > 400:
        address = address[:400]
    if len(state) > 80:
        state = state[:80]
    if len(hours) > 200:
        hours = hours[:200]
    return name, address, state, lat, lng, hours


def sql_str(s: str) -> str:
    return "N'" + s.replace("'", "''") + "'"


def main() -> int:
    if not RAW_PATH.is_file():
        print(f"Missing {RAW_PATH}; create it with your pasted lines.", file=sys.stderr)
        return 1
    raw = RAW_PATH.read_text(encoding="utf-8")
    rows: list[tuple[str, str, str, float, float, str]] = []
    bad: list[str] = []
    for i, line in enumerate(raw.splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        try:
            p = parse_line(line)
        except Exception:
            p = None
        if p is None:
            if re.search(r"\d+\.", line[:20]) or re.match(r"^[\d—]", line):
                bad.append(f"line {i}: {line[:120]}")
            continue
        rows.append(p)

    if not rows:
        print("No rows parsed.", file=sys.stderr)
        return 1

    values = ",\n    ".join(
        f"({sql_str(n)}, {sql_str(a)}, {sql_str(st)}, {lat}, {lng}, {sql_str(h)})" for n, a, st, lat, lng, h in rows
    )

    sql = f"""/*
  Auto-generated by build_branch_inserts_from_paste.py from branches_paste_raw.txt — {len(rows)} branches.
  Do not hand-edit: change the generator / raw paste and re-run `python3 database/build_branch_inserts_from_paste.py`.

  Prerequisites: the QMS database exists and dbo.BRANCHES / dbo.BRANCH_OPERATING_HOURS exist
  (start the API once so EF EnsureCreated builds the schema, or run database/schema.sql).
  If SSMS / VS Code shows "Invalid object name dbo.BRANCHES", you are on the wrong database or the
  schema was not created — fix that first, then refresh the IntelliSense cache.

  Every NOT NULL column of dbo.BRANCHES is given an explicit value. A database created by EF
  EnsureCreated has NO column defaults (e.g. AfterHoursDrainWindowMinutes), so relying on defaults fails.
  Values mirror the Branch entity defaults (QMS.Domain/Entities/Branch.cs) except SlotDurationMinutes (60).

  Safe to re-run: branches whose Name already exists in dbo.BRANCHES are skipped; BranchCode for new
  rows = MAX(existing BranchCode) + 1, 2, ... (empty DB starts at 101001). Runs in one transaction.
  Weekly hours for new branches: Mon–Fri 09:30–16:00, Sat–Sun closed (BRANCH_OPERATING_HOURS).
  Next: insert-service-types-all-branches.sql -> insert-service-queues-all-branches.sql ->
        insert-counters-8-closed-per-branch.sql -> insert-staff-all-branches.sql.

  Manual fix: Sungai Jarom had no coordinates in the source paste — approximate lat/lng were
  inserted in branches_paste_raw.txt; replace with surveyed values if required.
*/

USE QMS;
GO

/* Everything below is one batch: table variable @Branches does not survive GO. */
SET XACT_ABORT ON;
SET NOCOUNT ON;

DECLARE @Branches TABLE (
    RowOrd        INT IDENTITY(1, 1) PRIMARY KEY,
    [Name]        NVARCHAR(200) NOT NULL,
    [Address]     NVARCHAR(400) NOT NULL,
    [State]       NVARCHAR(80) NOT NULL,
    [Latitude]    FLOAT NOT NULL,
    [Longitude]   FLOAT NOT NULL,
    [OperatingHours] NVARCHAR(200) NULL
);

INSERT INTO @Branches ([Name], [Address], [State], [Latitude], [Longitude], [OperatingHours])
VALUES
    {values};

BEGIN TRANSACTION;

DECLARE @Base INT =
    (SELECT ISNULL(MAX([BranchCode]), 101000) FROM [dbo].[BRANCHES] WITH (UPDLOCK, HOLDLOCK));

INSERT INTO [dbo].[BRANCHES] (
    [Id],
    [BranchCode],
    [Name],
    [Address],
    [State],
    [Latitude],
    [Longitude],
    [SlotDurationMinutes],
    [GeofenceMeters],
    [ServiceZoneOffsetMinutes],
    [OpeningStatus],
    [OperatingHours],
    [ImageUrl],
    [MaxCapacity],
    [NextWeekBookingOpensOnDay],
    [OnlineEarlyCallMinutes],
    [CalledAbsentGraceMinutes],
    [AfterHoursDrainWindowMinutes]
)
SELECT
    NEWID() AS [Id],
    @Base + ROW_NUMBER() OVER (ORDER BY b.[RowOrd]) AS [BranchCode],
    b.[Name],
    b.[Address],
    b.[State],
    b.[Latitude],
    b.[Longitude],
    60 AS [SlotDurationMinutes],
    80 AS [GeofenceMeters],
    480 AS [ServiceZoneOffsetMinutes],
    0 AS [OpeningStatus],              /* BranchOpeningStatus.Open */
    b.[OperatingHours],
    CAST(NULL AS NVARCHAR(800)) AS [ImageUrl],
    CAST(NULL AS INT) AS [MaxCapacity],
    6 AS [NextWeekBookingOpensOnDay],  /* Saturday */
    10 AS [OnlineEarlyCallMinutes],
    5 AS [CalledAbsentGraceMinutes],
    60 AS [AfterHoursDrainWindowMinutes]
FROM @Branches AS b
WHERE NOT EXISTS (
    SELECT 1 FROM [dbo].[BRANCHES] AS x WHERE x.[Name] = b.[Name]);

PRINT CONCAT(N'Inserted BRANCHES rows: ', @@ROWCOUNT);

INSERT INTO dbo.BRANCH_OPERATING_HOURS (Id, BranchId, DayOfWeek, OpenTime, CloseTime, IsClosed)
SELECT
    NEWID(),
    br.Id,
    d.DayOfWeek,
    d.OpenTime,
    d.CloseTime,
    d.IsClosed
FROM dbo.BRANCHES AS br
CROSS JOIN (
    VALUES
        (N'Monday',    CAST('09:30' AS time), CAST('16:00' AS time), 0),
        (N'Tuesday',   CAST('09:30' AS time), CAST('16:00' AS time), 0),
        (N'Wednesday', CAST('09:30' AS time), CAST('16:00' AS time), 0),
        (N'Thursday',  CAST('09:30' AS time), CAST('16:00' AS time), 0),
        (N'Friday',    CAST('09:30' AS time), CAST('16:00' AS time), 0),
        (N'Saturday',  NULL, NULL, 1),
        (N'Sunday',    NULL, NULL, 1)
) AS d(DayOfWeek, OpenTime, CloseTime, IsClosed)
WHERE br.BranchCode > @Base
  /* Per (BranchId, DayOfWeek): avoids a duplicate key on IX_BRANCH_OPERATING_HOURS_BranchId_DayOfWeek. */
  AND NOT EXISTS (
      SELECT 1
      FROM dbo.BRANCH_OPERATING_HOURS AS h
      WHERE h.BranchId = br.Id AND h.DayOfWeek = d.DayOfWeek);

PRINT CONCAT(N'Inserted BRANCH_OPERATING_HOURS rows: ', @@ROWCOUNT);

COMMIT TRANSACTION;

SELECT [BranchCode], [Name], [Id] FROM [dbo].[BRANCHES] WHERE [BranchCode] > @Base ORDER BY [BranchCode];
GO
"""
    OUT_PATH.write_text(sql, encoding="utf-8")
    print(f"Wrote {OUT_PATH} ({len(rows)} rows).")
    if bad:
        print("Skipped / unparsed lines (review branches_paste_raw.txt):", file=sys.stderr)
        for b in bad[:40]:
            print("  ", b, file=sys.stderr)
        if len(bad) > 40:
            print(f"  ... and {len(bad) - 40} more", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
